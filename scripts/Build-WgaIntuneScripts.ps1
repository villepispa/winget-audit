#Requires -Version 5.1
<#
.SYNOPSIS
  Merges winget-audit detect sources into standalone Intune detection scripts.

.DESCRIPTION
  **Safety tier: 2** (writes generated bundles to dist/intune; no network).

  Concatenates module sources listed in scripts/intune/bundle-order.json, appends
  Presence and UpToDate entry templates, and emits
  Detect-WinGetPackagePresent.ps1 and Detect-WinGetPackageCurrent.ps1.
  Exit 0 on success. Pattern mirrors driver-store-manager Build-DsmIntuneScripts.ps1.

.PARAMETER OutputDirectory
  Output folder for generated scripts. Default: dist/intune under project root.

.PARAMETER AgentSummary
  Write exactly one line to the success stream so agents can use a single
  pwsh -NoProfile -File invocation (no Shell compound with if ($LASTEXITCODE)):
  WGA-BUILD-OK presentBytes=N currentBytes=M sources=K on exit 0;
  WGA-BUILD-FAIL exit=N on failure.

.EXAMPLE
  pwsh -NoProfile -File .\scripts\Build-WgaIntuneScripts.ps1

.EXAMPLE
  pwsh -NoProfile -File .\scripts\Build-WgaIntuneScripts.ps1 -AgentSummary

.EXAMPLE
  powershell.exe -NoProfile -ExecutionPolicy Bypass -File .\scripts\Build-WgaIntuneScripts.ps1

.NOTES
  Rebuild after changing src/WinGet.Audit or Entry templates. Generated
  dist/ files are auto-generated — edit the module and re-run this script.
  deploy/intune/ stubs stay thin for EAC ≤50 KB; this output is for Proactive
  Remediation / SCCM detect when the product tree is not on the endpoint.

.LINK
  docs/pilot-intune-detect.md
#>
[CmdletBinding()]
param(
    [string] $OutputDirectory,

    [switch] $AgentSummary
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$projectRoot = Resolve-Path (Join-Path $PSScriptRoot '..')
$manifestPath = Join-Path $PSScriptRoot 'intune\bundle-order.json'

if (-not $OutputDirectory) {
    $OutputDirectory = Join-Path $projectRoot 'dist\intune'
}

if (-not (Test-Path -LiteralPath $manifestPath)) {
    throw "Bundle manifest not found: $manifestPath"
}

$manifest = Get-Content -LiteralPath $manifestPath -Raw -Encoding UTF8 | ConvertFrom-Json
$moduleRoot = Join-Path $projectRoot $manifest.moduleRootRelative

function Get-WgaBundledSource {
    param(
        [string[]] $RelativePaths
    )

    $parts = [System.Collections.Generic.List[string]]::new()

    foreach ($rel in $RelativePaths) {
        $full = Join-Path $moduleRoot ($rel -replace '/', '\')
        if (-not (Test-Path -LiteralPath $full)) {
            throw "Missing source file: $full"
        }

        $content = Get-Content -LiteralPath $full -Raw -Encoding UTF8
        $parts.Add("#region WGA source: $rel`r`n$content`r`n#endregion WGA source: $rel") | Out-Null
    }

    return ($parts -join "`r`n`r`n")
}

function New-WgaStandaloneScript {
    param(
        [string] $ScriptType,
        [string] $EntryTemplatePath,
        [string] $OutputFileName,
        [string] $BundleBody
    )

    $entry = Get-Content -LiteralPath $EntryTemplatePath -Raw -Encoding UTF8
    $generatedAt = Get-Date -Format 'yyyy-MM-dd HH:mm:ss K'
    $psVersion = $PSVersionTable.PSVersion.ToString()

    $header = @"
# <auto-generated>
# WinGet.Audit — Intune $ScriptType script
# Generated: $generatedAt
# Builder host PS: $psVersion
# Do not edit by hand; change src/WinGet.Audit and run scripts/Build-WgaIntuneScripts.ps1
# </auto-generated>
#Requires -Version 5.1

Set-StrictMode -Version Latest

"@

    $full = $header + $BundleBody + "`r`n`r`n" + $entry
    $outPath = Join-Path $OutputDirectory $OutputFileName

    if (-not (Test-Path -LiteralPath $OutputDirectory)) {
        New-Item -ItemType Directory -Path $OutputDirectory -Force | Out-Null
    }

    if ($PSVersionTable.PSVersion.Major -ge 6) {
        Set-Content -LiteralPath $outPath -Value $full -Encoding utf8NoBOM
    }
    else {
        Set-Content -LiteralPath $outPath -Value $full -Encoding UTF8
    }

    return $outPath
}

try {
    $bundleBody = Get-WgaBundledSource -RelativePaths @($manifest.sources)
    $templatesRoot = Join-Path $PSScriptRoot 'intune\templates'

    $presentPath = New-WgaStandaloneScript -ScriptType 'Detection (Presence)' `
        -EntryTemplatePath (Join-Path $templatesRoot 'Detect-WinGetPackagePresent.Entry.ps1') `
        -OutputFileName 'Detect-WinGetPackagePresent.ps1' `
        -BundleBody $bundleBody

    $currentPath = New-WgaStandaloneScript -ScriptType 'Detection (UpToDate)' `
        -EntryTemplatePath (Join-Path $templatesRoot 'Detect-WinGetPackageCurrent.Entry.ps1') `
        -OutputFileName 'Detect-WinGetPackageCurrent.ps1' `
        -BundleBody $bundleBody

    $presentSize = (Get-Item -LiteralPath $presentPath).Length
    $currentSize = (Get-Item -LiteralPath $currentPath).Length

    [pscustomobject]@{
        PresentScript   = $presentPath
        CurrentScript   = $currentPath
        PresentBytes    = $presentSize
        CurrentBytes    = $currentSize
        SourceFileCount = @($manifest.sources).Count
    } | Format-List

    Write-Output 'Upload Present and/or Current to Intune (64-bit, SYSTEM or user as needed).'
    Write-Output 'One question per script. Set WGA_PACKAGE_ID. See docs/pilot-intune-detect.md.'
    Write-Output 'EAC stubs remain under deploy/intune/.'

    if ($AgentSummary) {
        Write-Output ("WGA-BUILD-OK presentBytes={0} currentBytes={1} sources={2}" -f `
            $presentSize, $currentSize, @($manifest.sources).Count)
    }
}
catch {
    if ($AgentSummary) {
        Write-Output ("WGA-BUILD-FAIL exit=1 error={0}" -f $_.Exception.Message)
    }
    throw
}
